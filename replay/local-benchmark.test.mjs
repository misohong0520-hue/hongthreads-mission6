const codec={protect:async value=>Buffer.concat([Buffer.from('test-only:'),value]),unprotect:async value=>value.subarray(10)};
async function temporary(t){
  const directory=await mkdtemp(join(tmpdir(),'dreaths-local-test-'));
  t.after(async()=>{const target=resolve(directory);assert.ok(target.startsWith(resolve(tmpdir())+sep+'dreaths-local-test-'));await rm(target,{recursive:true,force:true})});return directory;
}
test('local key survives restart, rejects tampering and rotates without accepting an upstream session',async t=>{
  const directory=await temporary(t),store=await createLocalBenchmarkStore({directory,...codec});
  const first=await store.issueToken();assert.ok(await store.verifyToken(first.token));
  const restarted=await createLocalBenchmarkStore({directory,...codec});
  assert.ok((await restarted.issueToken()).token===first.token,'restart must retain key');
  const changed=first.token.split('.');changed[1]=Buffer.from('{"iss":"original"}').toString('base64url');
  assert.equal(await restarted.verifyToken(changed.join('.')),null);
  assert.equal(await restarted.verifyToken('original-session-token'),null);
  assert.equal(await restarted.verifyToken(first.token.slice(0,-3)+'xyz'),null);
  const rotated=await restarted.issueToken({rotate:true});assert.ok(rotated.token!==first.token);
  assert.equal(await restarted.verifyToken(first.token),null);assert.ok(await restarted.verifyToken(rotated.token));
  assert.ok(!JSON.stringify(await restarted.status()).includes(rotated.token));
});
