test('source-observed link and stabilization actions update flags, filters and summary atomically',async t=>{
  const directory=await temporary(t),store=await createLocalBenchmarkStore({directory,...codec}),folder=await store.createFolder('분류');
  const a=await store.saveScrap({raw_content:'first fixture',folder_id:folder.id}),b=await store.saveScrap({raw_content:'second fixture',folder_id:folder.id}),c=await store.saveScrap({raw_content:'third fixture'});
  const body={action:'SAVE_LINK',scrap_id:a.id,raw_content:'first edited',custom_guide:'원본 가이드',folder_id:folder.id,
    affiliate_type:'COUPANG',affiliate_url:'https://link.coupang.com/a/fixture',affiliate_meta:{productName:'검증 상품',productPrice:1000,attachProductImage:true,customGuide:'원본 가이드'}};
  const linked=await store.applyAction(body);assert.equal(linked.success,true);assert.equal(linked.data.has_affiliate_link,true);assert.equal(linked.data.is_stabilization,false);
  let rows=await store.listScraps({view_mode:'MINE',link_filter:'LINKED',folder_id:folder.id});
  assert.equal(rows.total,1);assert.deepEqual(rows.link_summary,{all:2,linked:1,stabilization:0,unlinked:1});
  assert.equal(rows.data[0].affiliate_meta.productName,'검증 상품');
  await store.applyAction({action:'SAVE_STABILIZATION',scrap_id:b.id,affiliate_type:'STABILIZATION',custom_guide:'안정화 가이드'});
  rows=await store.listScraps({link_filter:'STABILIZATION'});assert.equal(rows.total,1);assert.equal(rows.data[0].id,b.id);assert.equal(rows.data[0].has_affiliate_link,false);
  await assert.rejects(store.applyAction({action:'BULK_SET_STABILIZATION',ids:[a.id,999]}),{code:'LOCAL_SCRAP_NOT_FOUND'});
  assert.equal((await store.getScrap(a.id)).has_affiliate_link,true,'failed bulk must not partly modify rows');
  await store.applyAction({action:'BULK_SET_STABILIZATION',ids:[a.id,c.id],view_mode:'MINE'});
  assert.equal((await store.listScraps({link_filter:'STABILIZATION'})).total,3);
  assert.equal((await store.getScrap(a.id)).affiliate_url,'');
  await store.applyAction({action:'REMOVE_LINK',scrap_id:a.id});
  assert.equal((await store.getScrap(a.id)).raw_content,'first edited');assert.equal((await store.getScrap(a.id)).custom_guide,'원본 가이드');
  await store.applyAction({action:'BULK_REMOVE_PURPOSE',ids:[b.id,c.id]});
  const restarted=await createLocalBenchmarkStore({directory,...codec});rows=await restarted.listScraps({link_filter:'UNLINKED'});
  assert.equal(rows.total,3);assert.deepEqual(rows.link_summary,{all:3,linked:0,stabilization:0,unlinked:3});
  assert.equal((await restarted.getScrap(a.id)).affiliate_meta,null);
  await assert.rejects(restarted.applyAction({...body,affiliate_url:'javascript:alert(1)'}),{code:'INVALID_AFFILIATE_URL'});
  await assert.rejects(restarted.listScraps({view_mode:'ALL_USERS'}),{code:'LOCAL_SHARED_LIBRARY_UNAVAILABLE'});
  await assert.rejects(restarted.applyAction({action:'COPY_WITH_LINK',source_scrap_id:a.id}),{code:'LOCAL_SHARED_LIBRARY_UNAVAILABLE'});
});
